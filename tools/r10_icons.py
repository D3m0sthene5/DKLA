def main():
    html = open(HTML, encoding='utf-8').read()
    m = re.search(r'<script id="seedData"[^>]*>', html); s0, e0 = m.end(), html.find('</script>', m.end())
    data = json.loads(html[s0:e0])
    m = re.search(r'<script id="dklaIcons"[^>]*>', html); s1, e1 = m.end(), html.find('</script>', m.end())
    icons = json.loads(html[s1:e1])
    nodes = {n['id']: n for n in data['nodes']}
    # 1. uniqueness and validity
    seen = collections.Counter((v[0], v[1]) for v in ICONS.values())
    dupes = [k for k, c in seen.items() if c > 1]
    assert not dupes, f'duplicate icons: {dupes}'
    paths = dict(icons['paths']); paths.update(PATHS)
    mods = dict(MODS)
    for v in ICONS.values():
        if v[1] and v[1] not in mods and v[1] in paths:
            mods[v[1]] = paths[v[1]]
    bad = [k for k, v in ICONS.items() if v[0] not in paths or (v[1] and v[1] not in mods)]
    assert not bad, f'unknown motif or modifier: {bad}'
    missing = [k for k in ICONS if k not in nodes]
    if missing:
        print('note: not in atlas yet (skipped):', missing)
    cases = [n['id'] for n in data['nodes'] if n['kind'] == 'Case']
    uncovered = [c for c in cases if c not in ICONS]
    assert not uncovered, f'cases without an icon: {uncovered}'
    # 2. write
    icons['paths'] = paths
    icons['modifiers'] = mods
    for cid, (motif, mod, caption) in ICONS.items():
        if cid not in nodes:
            continue
        icons['records'][cid] = {'motif': motif, 'modifier': mod, 'label': caption, 'basis': 'hand-drawn', 'status': 'unique',
                                 'rationale': caption, 'sources': (nodes[cid].get('sources') or [])[:1]}
        nodes[cid]['mnemonic'] = {'key': motif, 'modifier': mod, 'rationale': caption}
    icons['coverage'] = {'records': len(icons['records']), 'caseAccounts': len(cases), 'uniqueCaseIcons': len(cases),
                         'glyphs': len(paths), 'modifiers': len(mods), 'assignmentMethod': 'one hand-chosen glyph per case, no two alike (revision 10)'}
    icons['scope'] = 'Every case has its own icon drawn from its facts; concepts, rules and notes keep one symbol each.'
    def dump(o):
        s = json.dumps(o, ensure_ascii=False, separators=(',', ':')); assert '</' not in s; return s
    html = html[:s0] + dump(data) + html[e0:s1] + dump(icons) + html[e1:]
    open(HTML, 'w', encoding='utf-8').write(html)
    print(f'{len(cases)} cases, {len(paths)} glyphs, {len(MODS)} modifiers; icons written')


if __name__ == '__main__':
    main()
