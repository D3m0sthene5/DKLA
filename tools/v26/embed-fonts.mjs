/* Writes src/features/v26/release-font.css: the site's two embedded typefaces
   (owner's option F, 11 November 2026), each as unmodified upstream WOFF2 bytes
   in base64 @font-face rules with its full SIL Open Font License, so the page
   looks the same on every machine and works offline with no font request.

   Only the weights the site uses are embedded. Run after changing the list:
     node tools/v26/embed-fonts.mjs
   tools/verify/data_guard.py checks that every listed file and licence is in the CSS. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const assets = new URL('./assets/', import.meta.url);
export const families = [
  // Titles, the version label, top-bar buttons and course names.
  { family: 'DKLA Exo 2', slug: 'exo-2', licence: 'Exo2-OFL.txt', weights: [400, 600] },
  // Labels, interface and reading text. 550 renders with 600, 650 with 700.
  { family: 'DKLA Inter', slug: 'inter', licence: 'Inter-OFL.txt', weights: [400, 500, 600, 700] },
];
export const fontFile = (slug, weight) => `${slug}-latin-${weight}-normal.woff2`;

function css() {
  const parts = [
    '/* Embedded, unmodified Exo 2 and Inter (Fontsource 5.3.0, latin subset, WOFF2). No network fetch.\n' +
      '   Generated by tools/v26/embed-fonts.mjs; see tools/v26/assets/README.md for hashes. */',
  ];
  for (const { family, slug, licence, weights } of families) {
    const text = readFileSync(new URL(licence, assets), 'utf8').replace(/\r\n/g, '\n').trim();
    parts.push(`/* ${family}: ${weights.join(', ')}\n${text}\n*/`);
    for (const weight of weights) {
      const bytes = readFileSync(new URL(fontFile(slug, weight), assets)).toString('base64');
      parts.push(
        `@font-face{font-family:'${family}';src:url(data:font/woff2;base64,${bytes}) format("woff2");` +
          `font-weight:${weight};font-style:normal;font-display:swap}`,
      );
    }
  }
  return parts.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = new URL('../../src/features/v26/release-font.css', import.meta.url);
  writeFileSync(out, css());
  console.log('Wrote', fileURLToPath(out));
}
