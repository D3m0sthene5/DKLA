/* Writes src/features/clock/clock-font.css: the New York clock's typeface,
   JetBrains Mono Bold, embedded as base64 so the page needs no font request.
   The font bytes are unmodified and the full SIL Open Font License travels
   with them (see tools/clock/assets/README.md).

     node tools/clock/font.mjs           rewrite the CSS
     node tools/clock/font.mjs --check   fail if the CSS is missing the font or its licence */
import fs from 'node:fs';
import path from 'node:path';
import { root } from '../runtime.mjs';

const assets = path.join(root, 'tools/clock/assets');
const target = path.join(root, 'src/features/clock/clock-font.css');
const woff2 = fs.readFileSync(path.join(assets, 'jetbrains-mono-latin-700-normal.woff2'));
const licence = fs.readFileSync(path.join(assets, 'OFL.txt'), 'utf8').replace(/\r\n/g, '\n').trim();
const data = woff2.toString('base64');

if (process.argv.includes('--check')) {
  const css = fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  if (!css.includes(data)) throw Error('clock-font.css does not embed tools/clock/assets/*.woff2 unchanged');
  if (!css.includes(licence)) throw Error('clock-font.css is missing the JetBrains Mono licence');
  console.log(JSON.stringify({ pass: true, font: 'DKLA JetBrains Mono 700', bytes: woff2.length }));
} else {
  fs.writeFileSync(
    target,
    `/* New York clock typeface (clock.css): JetBrains Mono Bold, latin subset,
unmodified from the npm package @fontsource/jetbrains-mono 5.3.0. Embedded so
the page makes no font request. Generated by tools/clock/font.mjs.

${licence}
*/
@font-face {
  font-family: 'DKLA JetBrains Mono';
  font-style: normal;
  font-weight: 700;
  font-display: swap;
  src: url('data:font/woff2;base64,${data}')
    format('woff2');
}
`,
  );
  console.log(`Wrote ${path.relative(root, target)} (${woff2.length} font bytes).`);
}
